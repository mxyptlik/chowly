import { chromium } from "@playwright/test";
import { mkdir } from "node:fs/promises";
import { resolve } from "node:path";

const evidence = resolve(import.meta.dirname, "../../docs/verification/screenshots/08-reservations");
await mkdir(evidence, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
await page.goto("http://localhost:3000/login");
await page.getByLabel("Work email").fill("pilot1.manager@demo.chowly.ng");
await page.getByLabel("Password").fill("ChowlyDemo!2026");
await page.getByRole("button", { name: /sign in to chowly/i }).click();
await page.waitForURL("**/ops");
await page.goto("http://localhost:3000/manage/reservations", { waitUntil: "networkidle" });
const row = page.locator(".admin-row").filter({ hasText: "Reservation Browser Guest" }).first();
await row.waitFor();
await row.getByRole("button", { name: "Confirm" }).click();
await page.getByText("Reservation confirmed.").waitFor();
await page.screenshot({ path: resolve(evidence, "03-manager-reservation-confirmed.png"), fullPage: true });
console.log(JSON.stringify({ row: await row.innerText(), body: (await page.locator("body").innerText()).slice(-900) }, null, 2));
await browser.close();
