import { chromium } from "@playwright/test";
import { mkdir } from "node:fs/promises";
import { resolve } from "node:path";

const evidence = resolve(import.meta.dirname, "../../docs/verification/screenshots/08-reservations");
await mkdir(evidence, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
await page.goto("http://localhost:3000/r/mango-ash-hospitality/mango-ash-victoria-island/reserve", { waitUntil: "networkidle" });
console.log("RESERVATION_STEP", "form-opened");
await page.getByLabel("Your name").fill("Reservation Browser Guest");
await page.getByLabel("Phone number").fill("08091112222");
await page.getByLabel("Party size").fill("3");
await page.getByLabel("Preferred date and time").fill("2026-10-15T19:00");
await page.getByLabel("Note").fill("Window seat if possible.");
await page.getByRole("button", { name: "Request reservation" }).click();
console.log("RESERVATION_STEP", "request-submitted");
await page.waitForTimeout(1_000);
console.log("RESERVATION_PAGE", page.url(), (await page.locator("body").innerText()).slice(-1200));
await page.getByText("You’re").waitFor();
await page.screenshot({ path: resolve(evidence, "01-reservation-success.png"), fullPage: true });
const successUrl = page.url();
const token = new URL(successUrl).searchParams.get("token");
if (!token) throw new Error("Reservation success page did not provide its private capability.");
await page.goto(`http://localhost:3000/r/mango-ash-hospitality/mango-ash-victoria-island/reserve/confirmation?token=${encodeURIComponent(token)}`, { waitUntil: "networkidle" });
await page.getByRole("button", { name: "Save changes" }).waitFor();
await page.locator('input[type="number"]').fill("4");
await page.getByRole("button", { name: "Save changes" }).click();
await page.getByText("Updated for restaurant review.").waitFor();
await page.getByRole("button", { name: "Create check-in QR" }).click();
await page.getByText("Your private check-in QR is ready.").waitFor();
await page.screenshot({ path: resolve(evidence, "02-reservation-managed-qr.png"), fullPage: true });
console.log(JSON.stringify({ successPath: new URL(successUrl).pathname, confirmationPath: page.url().split("?")[0], text: (await page.locator("body").innerText()).slice(0, 1300) }, null, 2));
await browser.close();
